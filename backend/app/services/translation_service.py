        """Returns the native language translation for a district"""
        if not district_name or lang == "en":
            return district_name
        data = cls.DISTRICT_TRANSLATIONS.get(district_name.strip())
        if data and lang in data:
            return data[lang]
        for k, v in cls.DISTRICT_TRANSLATIONS.items():
            if k.lower() == district_name.strip().lower():
                return v.get(lang, district_name)
        return district_name
